"""Render docs/evals/RESULTS.md from the result receipts in docs/evals/results (numbers are never typed by hand).

    python -m analysis.evals.report
"""
from __future__ import annotations

import json
from pathlib import Path

from analysis.evals.routing import RESULTS

OUT = RESULTS.parent / "RESULTS.md"
MODELS = ("gpt-oss-20b", "gpt-oss-120b", "qwen3.8-27b")


def _j(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(v, d=1):
    return "—" if v is None or v != v else f"{v * 100:.{d}f}"


def retrieval_table(lines):
    for split in ("dev", "val", "test"):
        r = _j(f"retrieval-{split}.json")
        if not r:
            continue
        lines += [f"### Retrieval — {split} ({r['n']} questions, corpus {r['corpus_sha256'][:12]})", "",
                  "| Configuration | Recall@1 | Recall@3 | Recall@5 | Hit@5 | MRR | nDCG@5 | P@5 | Abstain P / R | p50 ms | p95 ms |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|"]
        for name, c in r["configs"].items():
            a = c.get("abstain") or {}
            lines.append(f"| {name} | {c['recall@1']:.3f} | {c['recall@3']:.3f} | {c['recall@5']:.3f} | {c['hit@5']:.3f} | "
                         f"{c['mrr']:.3f} | {c['ndcg@5']:.3f} | {c['precision@5']:.3f} | "
                         f"{pct(a.get('precision'), 0)} / {pct(a.get('recall'), 0)} | {c['latency_ms']['p50']:.1f} | {c['latency_ms']['p95']:.1f} |")
        if r.get("model_loads"):
            lines += ["", "Model load and index time (s): " + ", ".join(f"{k} {v}" for k, v in r["model_loads"].items())]
        lines.append("")


def answers_table(lines):
    rows = []
    for split in ("dev", "val", "test"):
        for f in sorted(RESULTS.glob(f"answers-{split}-*.json")):
            a = json.loads(f.read_text())
            rows.append((split, f.stem.split(f"answers-{split}-")[1], a))
    if not rows:
        return
    lines += ["### Grounded answers", "",
              "| Split | Retriever | Correct (all facts) | Fact coverage | Primary cited | Faithful | Unsupported claims | Abstain right | Words | p95 ms |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for split, name, a in rows:
        lines.append(f"| {split} | {name} | {pct(a['answer_correctness'])} | {pct(a['fact_coverage'])} | {pct(a['citation_coverage'])} | "
                     f"{pct(a['faithfulness'])} | {pct(a['unsupported_claim_rate'])} | {pct(a['abstain_correct'])} | "
                     f"{a['mean_words']:.0f} | {a['latency_ms']['p95']:.1f} |")
    lines.append("")


def routing_tables(lines):
    names = {"studio": "Studio routing (chart vs decision)", "intent": "Question intent (9 classes)",
             "chart": "Chart planning (spec fields)", "multiturn": "Multi-turn chart conversations"}
    for task, title in names.items():
        lines += [f"### {title}", "", "| Split | Method | Accuracy | 95 % CI | n | p50 ms | Tokens | Note |",
                  "|---|---|---:|---|---:|---:|---:|---|"]
        for split in ("val", "test"):
            local = _j(f"routing-{task}-{split}-local.json") or {}
            before = _j(f"routing-{task}-{split}-local-before.json") or {}
            for label, res in [*((f"{m} (before)", r) for m, r in before.items()), *local.items()]:
                lines.append(_row(split, label, res, task))
            for m in MODELS:
                r = _j(f"routing-{task}-{split}-{m}.json")
                if r:
                    lines.append(_row(split, f"model: {m}", next(iter(r.values())), task))
        lines.append("")


def _row(split, label, res, task):
    lo, hi = res["ci95"]
    note = "BLOCKED: " + str(res["blocked"].get("http_status")) if res.get("blocked") else ""
    if task == "multiturn" and "turn_accuracy" in res:
        note = (note + " " if note else "") + f"turns {pct(res['turn_accuracy'])} %"
    p50 = (res.get("latency_ms") or {}).get("p50")
    return (f"| {split} | {label} | {pct(res['accuracy'])} | {pct(lo)}–{pct(hi)} | {res['answered']}/{res['n']} | "
            f"{p50 if p50 is not None else '—'} | {res.get('tokens', 0)} | {note} |")


def perf_table(lines):
    runs = [(f.stem, json.loads(f.read_text())) for f in sorted(RESULTS.glob("perf-*.json"))]
    if not runs:
        return
    actions = list(runs[0][1]["actions"])
    lines += ["### Worker latency (ms, p50 / p95)", "", "| Action | " + " | ".join(n for n, _ in runs) + " |",
              "|---|" + "---:|" * len(runs)]
    for a in actions:
        cells = []
        for _, r in runs:
            x = r["actions"].get(a)
            cells.append(f"{x['p50']:.0f} / {x['p95']:.0f}" if x else "—")
        lines.append(f"| {a} | " + " | ".join(cells) + " |")
    lines.append("")


def main() -> int:
    lines = ["# Evaluation results", "",
             "Generated by `python -m analysis.evals.report` from the receipts in `docs/evals/results/`. Methodology, "
             "splits and decision rules: [README.md](README.md).", ""]
    retrieval_table(lines)
    answers_table(lines)
    routing_tables(lines)
    perf_table(lines)
    table = json.loads((Path(__file__).resolve().parents[1] / "llm_routing.json").read_text())
    lines += ["### Routing table in effect (analysis/llm_routing.json)", "", "| Task | Method | Local | Model | p | Why |",
              "|---|---|---:|---:|---:|---|"]
    for task, e in sorted(table["tasks"].items()):
        lines.append(f"| {task} | {e.get('method')} | {pct(e.get('local_accuracy'))} | "
                     f"{pct(e.get('model_accuracy'))} {('(' + e['model'] + ')') if e.get('model') else ''} | "
                     f"{e.get('p_value', '—')} | {e.get('why') or ''} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
