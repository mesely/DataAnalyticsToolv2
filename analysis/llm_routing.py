"""Automatic choice between the local method and the language model, per task (v3 G6, AW-18).

There is no "use the model" checkbox any more. `analysis/llm_routing.json` (generated by
`python -m analysis.llm_eval.routing --table ...` from held-out measurements) says, for each task, whether the local
method, the model, or "local first, model when local cannot plan" is used. On top of that table:

- policy: an administrator can keep every request local (`CONTEXT_LLM_EXTERNAL=off`, or `{"external": false}` in
  `<LOCAL>/llm-policy.json`); nothing is sent to a provider then;
- budget: model calls stop for the day once `daily_tokens` (default 150,000, under Groq's free 200,000) is used;
- no provider configured: local.

Whatever is chosen, the reply is validated as before and the screen names the planner and the reason.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
from pathlib import Path

TABLE = Path(__file__).resolve().parent / "llm_routing.json"
DEFAULT_DAILY_TOKENS = 150_000
METHODS = ("local", "model", "local_then_model")


def _local_dir():
    from analysis import llm

    return Path(llm.LOCAL)


def table():
    try:
        value = json.loads(TABLE.read_text())
    except (OSError, ValueError):
        return {"tasks": {}}
    return value if isinstance(value, dict) and isinstance(value.get("tasks"), dict) else {"tasks": {}}


def entry(task):
    e = table()["tasks"].get(task) or {}
    method = e.get("method") if e.get("method") in METHODS else "local"
    return {**e, "method": method}


def policy():
    p = {"external": True, "daily_tokens": DEFAULT_DAILY_TOKENS}
    try:
        saved = json.loads((_local_dir() / "llm-policy.json").read_text())
        if isinstance(saved, dict):
            if saved.get("external") is False:
                p["external"] = False
            if isinstance(saved.get("daily_tokens"), int) and saved["daily_tokens"] >= 0:
                p["daily_tokens"] = saved["daily_tokens"]
    except (OSError, ValueError):
        pass
    if os.environ.get("CONTEXT_LLM_EXTERNAL", "").strip().lower() in {"off", "0", "false", "no"}:
        p["external"] = False
    return p


def _usage_path():
    return _local_dir() / "llm-usage.json"


def tokens_today():
    try:
        u = json.loads(_usage_path().read_text())
    except (OSError, ValueError):
        return 0
    return int(u.get("tokens", 0)) if u.get("date") == dt.date.today().isoformat() else 0


def record_usage(telemetry):
    n = (telemetry or {}).get("total_tokens")
    if not isinstance(n, int) or n <= 0:
        return
    path = _usage_path()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(json.dumps({"date": dt.date.today().isoformat(), "tokens": tokens_today() + n}))
        tmp.replace(path)
    except OSError:
        pass  # accounting must never break an analysis


def availability():
    """Why the model can or cannot be used right now: None when it can, otherwise a short reason code."""
    from analysis.llm import status

    if not status().get("configured"):
        return "not_configured"
    p = policy()
    if not p["external"]:
        return "policy_local_only"
    if tokens_today() >= p["daily_tokens"]:
        return "daily_budget"
    return None


def use_model(task, *, local_ok=True):
    """Whether to ask the model for this task now. `local_ok` is False when the local method could not plan."""
    method = entry(task)["method"]
    if method == "local" or availability() is not None:
        return False
    return method == "model" or not local_ok


def receipt(task, used, *, fallback=None):
    """What the screen shows next to a result: which planner ran and why (no secrets, no provider payload)."""
    e = entry(task)
    out = {"task": task, "method": e["method"], "used": used, "why": e.get("why"),
           "local_accuracy": e.get("local_accuracy"), "model_accuracy": e.get("model_accuracy"), "n": e.get("n"),
           "measured_at": e.get("measured_at"), "model": e.get("model"), "local_method": e.get("local_method")}
    blocked = availability()
    if blocked and e["method"] != "local":
        out["unavailable"] = blocked
    if fallback:
        out["fallback"] = fallback
    return out


# ------------------------------------------------------------------ cache (validated plans only)

def _cache_dir():
    return _local_dir() / "llm-cache"


def cache_key(task, *parts):
    from analysis.llm import status

    raw = json.dumps([task, status().get("model"), *parts], sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(raw.encode()).hexdigest()


def cache_get(key):
    try:
        return json.loads((_cache_dir() / (key + ".json")).read_text())
    except (OSError, ValueError):
        return None


def cache_put(key, value):
    try:
        d = _cache_dir()
        d.mkdir(parents=True, exist_ok=True)
        tmp = d / (key + ".tmp")
        tmp.write_text(json.dumps(value, ensure_ascii=False))
        tmp.replace(d / (key + ".json"))
    except OSError:
        pass
