"""Build the Context Layer glyph family from the raw Gemini outputs.

Input:  core/web/src/workbench/assets/glyphs/gemini-batch-*.json — the JSON objects Gemini returned, saved
        unchanged as provenance ({name: "<svg ...>...</svg>"}).
Output: core/web/src/workbench/glyphs.generated.ts — validated element lists rendered by Glyph.tsx with
        React.createElement (no innerHTML), and an optional contact sheet for visual review.

Validation (fails loudly): viewBox 0 0 24 24; only path/circle/line/polyline/rect; attribute allowlist; no
event handlers, references, styles or transforms; numeric coordinates inside 0..24; exactly one
<circle class="idx">. Geometry is never edited here: a glyph that fails is regenerated, not patched.
Run: .venv/bin/python -m tools.design.glyphs [--sheet out.html]
"""
from __future__ import annotations

import json
import re
import sys
from urllib.parse import quote
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "core/web/src/workbench/assets/glyphs"
OUT = ROOT / "core/web/src/workbench/glyphs.generated.ts"
CSS_OUT = ROOT / "core/web/src/workbench/glyphs.generated.css"
# Browser widgets (disclosure marker, select caret, date picker, checkbox mark) cannot host a React element, so the
# same glyphs are emitted as CSS data URIs: as masks (painted with currentColor) or, for a select's background,
# pre-inked with the theme's muted tone.
WIDGETS = {"disclosure": "chevron_right", "calendar": "calendar", "tick": "tick"}
CARET_INK = {"light": "#637086", "dark": "#a9b8cf"}
TAGS = {"path", "circle", "line", "polyline", "rect"}
ATTRS = {"d", "cx", "cy", "r", "x1", "y1", "x2", "y2", "points", "x", "y", "width", "height", "rx", "ry", "class",
         "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "opacity"}
REACT = {"stroke-width": "strokeWidth", "stroke-linecap": "strokeLinecap", "stroke-linejoin": "strokeLinejoin", "class": "className"}
NUM = re.compile(r"-?\d*\.?\d+(?:e-?\d+)?", re.I)


def load():
    """Later batches may revise an earlier glyph (the earlier output stays in its file as provenance)."""
    family, source = {}, {}
    files = sorted(SRC.glob("gemini-batch-*.json"), key=lambda f: int(re.search(r"(\d+)", f.stem).group(1)))
    for f in files:
        for name, svg in json.loads(f.read_text()).items():
            source[name] = f.name if name not in family else f"{f.name} (revises {source[name]})"
            family[name] = svg
    return family, source


def parse(name, svg):
    root = ET.fromstring(svg)
    if root.tag.split("}")[-1] != "svg" or root.attrib.get("viewBox") != "0 0 24 24":
        raise ValueError(f"{name}: root must be <svg viewBox='0 0 24 24'>")
    elements, idx = [], 0
    for node in root.iter():
        tag = node.tag.split("}")[-1]
        if node is root:
            continue
        if tag == "g":
            raise ValueError(f"{name}: groups are not part of the grammar")
        if tag not in TAGS:
            raise ValueError(f"{name}: tag {tag} not allowed")
        attrs = {}
        for key, value in node.attrib.items():
            key = key.split("}")[-1]
            if key not in ATTRS or key.lower().startswith("on") or "url(" in value.lower():
                raise ValueError(f"{name}: attribute {key} not allowed")
            # Path data mixes radii and flags with coordinates; it is checked visually on the contact sheet.
            if key in {"points", "cx", "cy", "x1", "y1", "x2", "y2", "x", "y"}:
                for n in NUM.findall(value):
                    if not -0.5 <= float(n) <= 24.5:
                        raise ValueError(f"{name}: coordinate {n} outside the 24 grid")
            attrs[REACT.get(key, key)] = value
        if tag == "circle" and "idx" in attrs.get("className", "").split():
            idx += 1
        elements.append([tag, attrs])
    if idx != 1:
        raise ValueError(f"{name}: needs exactly one index dot, found {idx}")
    if not 1 < len(elements) <= 8:
        raise ValueError(f"{name}: {len(elements)} elements (grammar allows 2..8 incl. the dot)")
    return elements


def data_uri(svg, ink="#000"):
    svg = re.sub(r"\s+", " ", svg.strip()).replace("currentColor", ink)
    return 'url("data:image/svg+xml,' + quote(svg, safe=" =:/,.-") + '")'


def widget_css(family):
    lines = ["/* Generated by tools/design/glyphs.py from assets/glyphs/gemini-batch-*.json; do not edit by hand. */", ":root {"]
    lines += [f"  --glyph-{key}: {data_uri(family[name])};" for key, name in WIDGETS.items()]
    lines += [f"  --glyph-caret-{theme}: {data_uri(family['chevron_down'], ink)};" for theme, ink in CARET_INK.items()]
    return "\n".join(lines + ["}", ""])


def main(argv):
    family, source = load()
    parsed, errors = {}, []
    for name, svg in sorted(family.items()):
        try:
            parsed[name] = parse(name, svg)
        except (ValueError, ET.ParseError) as e:
            errors.append(str(e))
    if errors:
        print("\n".join(errors))
        return 1
    body = json.dumps(parsed, indent=None, separators=(",", ":"), ensure_ascii=True)
    OUT.write_text(
        "// Generated by tools/design/glyphs.py from assets/glyphs/gemini-batch-*.json (Gemini outputs, unedited).\n"
        "// Do not edit by hand; regenerate. Rendered by Glyph.tsx as React elements, never as a raw markup string.\n"
        "export type GlyphElement = [\"path\" | \"circle\" | \"line\" | \"polyline\" | \"rect\", Record<string, string>];\n"
        f"export const GLYPHS: Record<string, GlyphElement[]> = {body};\n"
        f"export const GLYPH_SOURCE: Record<string, string> = {json.dumps(source, sort_keys=True)};\n")
    CSS_OUT.write_text(widget_css(family))
    if "--svg-sheet" in argv:
        out = Path(argv[argv.index("--svg-sheet") + 1])
        names = sorted(family)
        cols, cell_w, cell_h = 4, 190, 78
        rows = (len(names) + cols - 1) // cols
        panel_w, h = cols * cell_w + 24, rows * cell_h + 24
        parts = [f"<svg xmlns='http://www.w3.org/2000/svg' width='{panel_w}' height='{h * 2}' viewBox='0 0 {panel_w} {h * 2}'>",
                 "<style>text{font:11px system-ui}.l .idx{fill:#b9905b}.d .idx{fill:#d4ad72}</style>"]
        for p_i, (cls, bg, fg) in enumerate((("l", "#f6f7fa", "#1c2941"), ("d", "#0f1726", "#dfe6f3"))):
            ox, oy = 0, p_i * h
            parts.append(f"<rect x='0' y='{oy}' width='{panel_w}' height='{h}' fill='{bg}'/><g class='{cls}' color='{fg}' fill='{fg}'>")
            for i, n in enumerate(names):
                x, y = ox + 12 + (i % cols) * cell_w, oy + 12 + (i // cols) * cell_h
                inner = re.sub(r"^<svg[^>]*>|</svg>$", "", family[n].strip())
                cx = x
                for size in (16, 20, 24, 48):
                    parts.append(f"<svg x='{cx}' y='{y + 48 - size}' width='{size}' height='{size}' viewBox='0 0 24 24' fill='none' stroke='currentColor' stroke-width='1.75' stroke-linecap='round' stroke-linejoin='round'>{inner}</svg>")
                    cx += size + 10
                parts.append(f"<text x='{x}' y='{y + 64}' stroke='none'>{n}</text>")
            parts.append("</g>")
        parts.append("</svg>")
        out.write_text("".join(parts))
        print("svg sheet", out)
    if "--sheet" in argv:
        out = Path(argv[argv.index("--sheet") + 1])
        cells = "".join(
            f"<figure><div class='row'>" + "".join(f"<span style='width:{s}px;height:{s}px'>{family[n]}</span>" for s in (16, 20, 24, 48))
            + f"</div><figcaption>{n}</figcaption></figure>" for n in sorted(family))
        css = ("body{font:12px system-ui;margin:0;display:grid;grid-template-columns:1fr 1fr}section{padding:24px;display:grid;grid-template-columns:repeat(4,1fr);gap:16px}"
               ".light{background:#f6f7fa;color:#1c2941}.dark{background:#0f1726;color:#dfe6f3}figure{margin:0}.row{display:flex;gap:12px;align-items:end}"
               "span svg{width:100%;height:100%}.light .idx{fill:#b9905b}.dark .idx{fill:#d4ad72}figcaption{margin-top:6px;opacity:.7}")
        out.write_text(f"<!doctype html><meta charset=utf-8><style>{css}</style><section class=light>{cells}</section><section class=dark>{cells}</section>")
        print("sheet", out)
    print(f"{len(parsed)} glyphs -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
